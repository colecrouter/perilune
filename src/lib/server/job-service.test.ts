const bytes = new TextEncoder().encode(
	'; generated by OrcaSlicer 2.4\n; filament_type = PLA\n;TIME:120\nG28\nG1 X10 Y10\n'
);
async function create(
	filename = ':memory:',
	url = '',
	checkUser: (id: string, epoch: number) => boolean = (_id: string, epoch: number) => epoch === 0,
	liveFiles = false
) {
	const printer = makePrinterService(url ? 'moonraker' : 'simulator').pipe(
		Layer.provideMerge(ActionStoreLive)
	);
	const layer = JobServiceLive.pipe(
		Layer.provideMerge(printer),
		Layer.provide(SqliteClient.layer({ filename })),
		Layer.provide(Layer.succeed(JobsConfig, { moonrakerUrl: url, checkUser, liveFiles }))
	);
	const runtime = ManagedRuntime.make(layer);
	cleanup.push(() => runtime.dispose());
	const jobs = await runtime.runPromise(JobService);
	const service = await runtime.runPromise(PrinterService);
	return {
		runtime,
		jobs,
		printer: service,
		catalog: () => runtime.runPromise(SubscriptionRef.get(jobs.state)),
		snapshot: () => runtime.runPromise(SubscriptionRef.get(service.state))
	};
}
