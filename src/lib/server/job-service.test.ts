it('publishes a committed upload even if its caller aborts immediately before publication', async () => {
	const { runtime, jobs, catalog } = await create();
	const controller = new AbortController();
	const stagedState = await catalog();
	const update = vi.mocked(SubscriptionRef.update).getMockImplementation()!;
	let armed = true;
	vi.mocked(SubscriptionRef.update).mockImplementation(((ref: unknown, change: unknown) => {
		if (
			ref === jobs.state &&
			armed &&
			(change as (state: typeof stagedState) => typeof stagedState)(stagedState).files.some(
				(file) => file.name === 'committed.gcode'
			)
		) {
			armed = false;
			controller.abort();
		}
		return update(ref as Parameters<typeof update>[0], change as Parameters<typeof update>[1]);
	}) as typeof update);
	await runtime
		.runPromise(jobs.upload('committed.gcode', bytes), { signal: controller.signal })
		.catch(() => {});
	vi.restoreAllMocks();
	expect((await catalog()).files.map((file) => file.name)).toEqual(['committed.gcode']);
	const retry = await runtime.runPromise(jobs.upload('committed.gcode', bytes));
	expect((await catalog()).files[0]?.id).toBe(retry.id);
});
it('bounds queued live inspections, cancels abandoned upstream reads, and splits disconnected sessions', async () => {
	let metadataRequests = 0;
	let metadataClosed = false;
	const server = createServer((request, response) => {
		if (request.url?.startsWith('/server/files/list')) {
			response.setHeader('Content-Type', 'application/json');
			response.end(JSON.stringify({ result: [{ path: 'part.gcode', size: 100, modified: 1 }] }));
		} else {
			metadataRequests++;
			response.on('close', () => {
				metadataClosed = true;
			});
		}
	});
	await new Promise<void>((accept) => server.listen(0, '127.0.0.1', accept));
	cleanup.push(
		() =>
			new Promise<void>((accept) => {
				server.closeAllConnections();
				server.close(() => accept());
			})
	);
	const address = server.address() as { port: number };
	const { runtime, jobs, printer, catalog, snapshot } = await create(
		':memory:',
		`ws://127.0.0.1:${address.port}/websocket`
	);
	await expect.poll(async () => (await catalog()).files.length).toBe(1);
	const id = (await catalog()).files[0]!.id;
	const controller = new AbortController();
	const requests = Array.from({ length: 20 }, () =>
		runtime.runPromise(jobs.inspect(id), { signal: controller.signal }).catch(() => null)
	);
	await expect.poll(() => metadataRequests).toBe(1);
	await expect(runtime.runPromise(jobs.inspect(id))).rejects.toThrow('busy');
	controller.abort();
	await Promise.all(requests);
	await expect.poll(() => metadataClosed).toBe(true);
	await runtime.runPromise(
		printer.ingest({
			...(await snapshot()),
			connection: 'connected',
			klippy: 'ready',
			job: {
				filename: 'part.gcode',
				state: 'printing',
				progress: 10,
				layer: null,
				totalLayers: null,
				remainingMinutes: null
			}
		})
	);
	await expect.poll(async () => (await catalog()).runs.length).toBe(1);
	await runtime.runPromise(printer.ingest({ ...(await snapshot()), connection: 'disconnected' }));
	await expect.poll(async () => (await catalog()).runs[0]?.state).toBe('interrupted');
	await runtime.runPromise(
		printer.ingest({
			...(await snapshot()),
			connection: 'connected',
			job: { ...(await snapshot()).job, state: 'printing', progress: 2 }
		})
	);
	await expect.poll(async () => (await catalog()).runs.length).toBe(2);
	expect((await catalog()).runs.filter((run) => run.ended === null)).toHaveLength(1);
});
