const cleanup: Array<() => Promise<void>> = [];
afterEach(async () => {
	vi.mocked(SubscriptionRef.update).mockReset();
	for (const close of cleanup.splice(0).reverse()) await close();
});
const bytes = new TextEncoder().encode(
	'; generated by OrcaSlicer 2.4\n; filament_type = PLA\n;TIME:120\nG28\nG1 X10 Y10\n'
);
async function create(
	filename = ':memory:',
	url = '',
	checkUser: (id: string, epoch: number) => boolean = (_id: string, epoch: number) => epoch === 0
) {
	const printer = makePrinterService(url ? 'moonraker' : 'simulator').pipe(
		Layer.provideMerge(ActionStoreLive)
	);
	const layer = JobServiceLive.pipe(
		Layer.provideMerge(printer),
		Layer.provide(SqliteClient.layer({ filename })),
		Layer.provide(Layer.succeed(JobsConfig, { moonrakerUrl: url, checkUser }))
	);
	const runtime = ManagedRuntime.make(layer);
	cleanup.push(() => runtime.dispose());
	const jobs = await runtime.runPromise(JobService);
	const service = await runtime.runPromise(PrinterService);
	return {
		runtime,
		jobs,
		printer: service,
		catalog: () => runtime.runPromise(SubscriptionRef.get(jobs.state)),
		snapshot: () => runtime.runPromise(SubscriptionRef.get(service.state))
	};
}
it('deduplicates uploads, refuses overwrites and persists the library across restart', async () => {
	const directory = await mkdtemp(join(tmpdir(), 'perilune-job-test-'));
	cleanup.push(() => rm(directory, { recursive: true, force: true }));
	const filename = join(directory, 'jobs.sqlite');
	const first = await create(filename);
	const file = await first.runtime.runPromise(first.jobs.upload('bracket.gcode', bytes));
	const duplicate = await first.runtime.runPromise(first.jobs.upload('bracket.gcode', bytes));
	expect(duplicate.id).toBe(file.id);
	await expect(
		first.runtime.runPromise(
			first.jobs.upload('bracket.gcode', new TextEncoder().encode('G28\nG1 X20'))
		)
	).rejects.toThrow('different file');
	await first.runtime.runPromise(
		first.printer.submit({
			id: randomUUID(),
			command: { type: 'cancel', coolBed: false, coolNozzle: false }
		})
	);
	await expect.poll(async () => (await first.catalog()).runs[0]?.state).toBe('cancelled');
	const cancelledId = (await first.catalog()).runs[0]!.id;
	await first.runtime.dispose();
	const second = await create(filename);
	expect(
		(await second.catalog()).runs.some((run) => run.id === cancelledId && run.state === 'cancelled')
	).toBe(true);
	expect((await second.catalog()).files[0]).toMatchObject({
		id: file.id,
		name: 'bracket.gcode',
		metadata: { material: 'PLA' }
	});
});
it('rechecks authorization after waiting for the catalog lock and bounds admission', async () => {
	const { runtime, jobs, catalog } = await create();
	let release!: () => void;
	const gate = new Promise<void>((accept) => {
		release = accept;
	});
	let entered = false;
	const first = runtime.runPromise(
		jobs.upload(
			'first.gcode',
			bytes,
			Effect.promise(async () => {
				entered = true;
				await gate;
				return true;
			})
		)
	);
	await expect.poll(() => entered).toBe(true);
	let allowed = true;
	const queued = runtime
		.runPromise(
			jobs.upload(
				'revoked.gcode',
				bytes,
				Effect.sync(() => allowed)
			)
		)
		.then(
			() => false,
			() => true
		);
	allowed = false;
	release();
	await first;
	expect(await queued).toBe(true);
	expect((await catalog()).files.map((f) => f.name)).toEqual(['first.gcode']);
	const one = await runtime.runPromise(jobs.beginUpload);
	const two = await runtime.runPromise(jobs.beginUpload);
	await expect(runtime.runPromise(jobs.beginUpload)).rejects.toThrow('Two uploads');
	one();
	two();
});
it('starts a shared simulated print once, protects its file, and records cancellation', async () => {
	const { runtime, jobs, printer, snapshot, catalog } = await create();
	const file = await runtime.runPromise(jobs.upload('next.gcode', bytes));
	await runtime.runPromise(
		printer.submit({
			id: randomUUID(),
			command: { type: 'cancel', coolBed: false, coolNozzle: false }
		})
	);
	await expect.poll(async () => (await snapshot()).job.state).toBe('cancelled');
	const request = { id: randomUUID(), command: { type: 'start' as const, fileId: file.id } };
	await Promise.all([
		runtime.runPromise(printer.submit(request)),
		runtime.runPromise(printer.submit(request))
	]);
	await expect(
		runtime.runPromise(printer.submit({ ...request, id: randomUUID() }))
	).rejects.toThrow('pending');
	await expect.poll(async () => (await snapshot()).job.filename).toBe('next.gcode');
	expect((await snapshot()).job.runId).toBe(request.id);
	await expect(runtime.runPromise(jobs.remove(file.id))).rejects.toThrow('active');
	await expect.poll(async () => (await snapshot()).job.progress).toBeGreaterThan(0);
	await runtime.runPromise(
		printer.submit({
			id: randomUUID(),
			command: { type: 'cancel', coolBed: true, coolNozzle: true }
		})
	);
	await expect
		.poll(async () => (await catalog()).runs.find((run) => run.id === request.id)?.state)
		.toBe('cancelled');
	await runtime.runPromise(jobs.remove(file.id));
	expect((await catalog()).files).toHaveLength(0);
	expect((await catalog()).runs.some((run) => run.id === request.id)).toBe(true);
});
it('expires/revokes scoped keys and invalidates keys when the owner is recovered', async () => {
	let active = true;
	const { runtime, jobs } = await create(':memory:', '', (_id, epoch) => active && epoch === 0);
	const { token, key } = await runtime.runPromise(jobs.issueKey('owner', 0, 'Orca'));
	expect(await runtime.runPromise(jobs.validateKey(token))).toBe(true);
	active = false;
	expect(await runtime.runPromise(jobs.validateKey(token))).toBe(false);
	active = true;
	await runtime.runPromise(jobs.revokeKey('owner', key.id));
	expect(await runtime.runPromise(jobs.validateKey(token))).toBe(false);
	await expect(runtime.runPromise(jobs.issueKey('owner', 1, 'old epoch'))).rejects.toThrow(
		'active operator'
	);
});
