export const emptyMetadata = (): JobMetadata => ({
	slicer: null,
	material: null,
	estimatedSeconds: null,
	layerHeight: null,
	layers: null,
	filamentGrams: null,
	thumbnail: null
});
const hasControl = (value: string) => {
	for (let i = 0; i < value.length; i++) {
		const code = value.charCodeAt(i);
		if (code < 32 || code === 127) return true;
	}
	return false;
};
export function validGcodeName(value: string): boolean {
	return (
		value.length > 0 &&
		value.length <= 180 &&
		!/[\\/]/.test(value) &&
		!hasControl(value) &&
		value !== '.' &&
		value !== '..' &&
		/\.gcode$/i.test(value)
	);
}
export function safeRelativePath(value: string): boolean {
	return (
		value.length > 0 &&
		value.length <= 500 &&
		!/[\\?#%]/.test(value) &&
		!hasControl(value) &&
		value.split('/').every((part) => part !== '' && part !== '.' && part !== '..')
	);
}
export function startReason(snapshot: PrinterSnapshot, checkPending = true): string | null {
	const safety = safetyReason(snapshot.safety);
	if (safety) return safety;
	if (snapshot.liveRecovery) return snapshot.liveRecovery.message;
	if (snapshot.mode !== 'simulator' && !snapshot.liveControls)
		return 'Live printing is read-only until coordinated printer testing.';
	if (snapshot.configurationBusy) return 'Configuration recovery owns the printer.';
	if (snapshot.connection !== 'connected' || snapshot.klippy !== 'ready')
		return 'Reconnect to a ready printer before starting a job.';
	if (snapshot.storage !== 'healthy') return 'Action storage is recovering. Please wait.';
	if (snapshot.job.state === 'printing' || snapshot.job.state === 'paused')
		return 'Stop or finish the current print before starting another.';
	if (snapshot.motion.calibration || snapshot.motion.busy !== false)
		return 'Finish calibration or movement before starting a job.';
	if (
		checkPending &&
		snapshot.actions.some((action) => action.status === 'queued' || action.status === 'sending')
	)
		return 'Wait for the pending action to finish.';
	return null;
}
/** Inspect comments only. G-code is never executed or passed to a shell. */
export function parseGcode(bytes: Uint8Array): JobMetadata {
	const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
	if (text.includes('\0') || !/^\s*(?:N\d+\s+)?[GMT]\d+/im.test(text))
		throw new Error(
			'Choose a text G-code file containing printer commands. Binary G-code and 3MF are not supported yet.'
		);
	const result = emptyMetadata();
	const comments = text
		.split(/\r?\n/)
		.filter((line) => line.trimStart().startsWith(';'))
		.join('\n');
	result.slicer = comments.match(/generated by ([^\r\n;]{1,100})/i)?.[1]?.trim() ?? null;
	result.material =
		comments.match(/;\s*(?:filament_type|filament type)\s*[:=]\s*([^\r\n;]{1,80})/i)?.[1]?.trim() ??
		null;
	const numeric = (pattern: RegExp) => {
		const value = Number(comments.match(pattern)?.[1]);
		return Number.isFinite(value) && value > 0 ? value : null;
	};
	result.layerHeight = numeric(/;\s*layer_height\s*[:=]\s*([\d.]+)/i);
	result.layers = numeric(/;\s*(?:total layer number|layer_count)\s*[:=]\s*(\d+)/i);
	result.filamentGrams = numeric(
		/;\s*filament (?:used \[g\]|used \[grams\]|weight)\s*[:=]\s*([\d.]+)/i
	);
	result.estimatedSeconds = numeric(/;\s*TIME\s*:\s*(\d+)/i);
	if (result.estimatedSeconds === null) {
		const duration = comments.match(
			/(?:estimated printing time \(normal mode\)|model printing time)\s*[:=]\s*([^\r\n]+)/i
		)?.[1];
		if (duration) {
			let total = 0;
			for (const part of duration.matchAll(/([\d.]+)\s*([dhms])/g))
				total += Number(part[1]) * ({ d: 86400, h: 3600, m: 60, s: 1 }[part[2]!] ?? 0);
			result.estimatedSeconds = total > 0 ? total : null;
		}
	}
	// PNG only: opaque metadata never becomes SVG, HTML, or an upstream URL.
	for (const match of comments.matchAll(
		/;\s*thumbnail begin\s+\d+x\d+\s+\d+\s*\n([\s\S]*?);\s*thumbnail end/g
	)) {
		const base64 = match[1]!.replace(/^;\s*/gm, '').replace(/\s/g, '');
		if (
			base64.length <= 350_000 &&
			/^[A-Za-z0-9+/]*={0,2}$/.test(base64) &&
			base64.startsWith('iVBORw0KGgo')
		)
			result.thumbnail = `data:image/png;base64,${base64}`;
	}
	return result;
}
export function durationLabel(seconds: number | null): string {
	if (seconds === null) return 'Not reported';
	const minutes = Math.max(1, Math.round(seconds / 60));
	return minutes >= 60 ? `${Math.floor(minutes / 60)}h ${minutes % 60}m` : `${minutes}m`;
}
