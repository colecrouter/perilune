import { expect, it } from 'vite-plus/test';
import {
	calibrationDraftChange,
	CALIBRATION_PROPOSAL_LIFETIME,
	type CalibrationDraftProposal
} from './calibration-draft.js';
import { calculateExtrusion } from './extrusion.js';
import { configParts } from './configuration.js';
const now = 10_000_000;
const proposal: CalibrationDraftProposal = {
	id: 'proposal',
	ownerId: 'owner',
	createdAt: now,
	source: 'simulator',
	measurement: calculateExtrusion(7.5, 70, 22)
};
const source =
	'\uFEFF# keep\r\n[extruder]\r\nrotation_distance = 7.5  # measured\r\ngear_ratio: 50:10\r\n\r\n[printer]\r\nmax_velocity: 180 # another draft edit\r\n';
const tail =
	'\r\n#*# <---------------------- SAVE_CONFIG ---------------------->\r\n#*# DO NOT EDIT THIS BLOCK OR BELOW. The contents are auto-generated.\r\n#*#\r\n#*# [probe]\r\n#*# z_offset = 1.2\r\n';
it('replaces only the measured setting while preserving drafts, comments, gearing, BOM, CRLF and generated bytes', () => {
	const change = calibrationDraftChange(source + tail, proposal, 'simulator', true, now);
	expect(change.text).toBe((source + tail).replace('7.5  # measured', '7.200  # measured'));
	expect(configParts(change.text).generated).toBe(configParts(source + tail).generated);
});
it('recomputes the result from measurements rather than trusting the transferred proposal', () => {
	const tampered = { ...proposal, measurement: { ...proposal.measurement, proposed: 999 } };
	expect(
		calibrationDraftChange(source, tampered, 'simulator', true, now).measurement.proposed
	).toBe(7.2);
});
it('refuses mismatched mode, expired results, changed baselines and no-op changes', () => {
	expect(() => calibrationDraftChange(source, proposal, 'moonraker', true, now)).toThrow(
		/Simulator/
	);
	expect(() =>
		calibrationDraftChange(
			source,
			proposal,
			'simulator',
			true,
			now + CALIBRATION_PROPOSAL_LIFETIME + 1
		)
	).toThrow(/expired/);
	expect(() =>
		calibrationDraftChange(source.replace('7.5', '7.6'), proposal, 'simulator', true, now)
	).toThrow(/differs/);
	expect(() =>
		calibrationDraftChange(
			source,
			{ ...proposal, measurement: calculateExtrusion(7.5, 70, 20) },
			'simulator',
			true,
			now
		)
	).toThrow(/No configuration change/);
});
it('blocks missing, repeated, generated and multiline options', () => {
	for (const text of [
		'[extruder]\ngear_ratio: 50:10\n',
		source + '[extruder]\nrotation_distance: 7.5\n',
		source + '[extruder ]\nrotation_distance: 7.5\n',
		source.replace('gear_ratio:', '  continuation\ngear_ratio:'),
		source +
			tail.replace('[probe]', '[extruder]').replace('z_offset = 1.2', 'rotation_distance = 7.5')
	]) {
		expect(() => calibrationDraftChange(text, proposal, 'simulator', true, now)).toThrow();
	}
});
it('requires include review and never edits a generated-looking tail with unexpected content', () => {
	expect(() =>
		calibrationDraftChange('[include extruder.cfg]\n' + source, proposal, 'simulator', false, now)
	).toThrow(/included/);
	expect(() =>
		calibrationDraftChange(source + tail + '# ordinary comment\n', proposal, 'simulator', true, now)
	).toThrow(/warning/);
});
