import assert from 'node:assert/strict';
import { request as httpRequest } from 'node:http';
import { spawn } from 'node:child_process';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { chromium } from 'playwright';
import { authenticate } from './smoke-auth-helper.mjs';
const directory = await mkdtemp(join(tmpdir(), 'perilune-progressive-'));
const filename = join(directory, 'printer.sqlite');
const base = 'http://127.0.0.1:4197';
let browser,
	child,
	logs = '';
try {
	child = spawn(process.execPath, ['scripts/server.mjs'], {
		env: {
			...process.env,
			HOST: '127.0.0.1',
			PORT: '4197',
			PERILUNE_ORIGIN: base,
			PERILUNE_DATABASE: filename,
			PERILUNE_MOONRAKER_URL: '',
			PERILUNE_MOONRAKER_API_KEY: '',
			PERILUNE_CAMERA_COMPANION_URL: '',
			PERILUNE_LIVE_MESH: 'false',
			PERILUNE_LIVE_CONFIGURATION: 'false'
		},
		stdio: ['ignore', 'pipe', 'pipe']
	});
	child.stdout.on('data', (c) => (logs += c));
	child.stderr.on('data', (c) => (logs += c));
	for (let i = 0; ; i++) {
		try {
			if ((await fetch(base + '/health')).ok) break;
		} catch {}
		if (i > 100 || child.exitCode !== null) throw new Error(logs);
		await new Promise((r) => setTimeout(r, 100));
	}
	browser = await chromium.launch({ headless: true });
	const native = await browser.newContext({
		javaScriptEnabled: false,
		viewport: { width: 1280, height: 900 }
	});
	await authenticate(native, base, filename);
	const page = await native.newPage();
	await page.goto(base + '/');
	assert.equal(await page.title(), 'Overview · Perilune');
	assert.ok(!(await page.textContent('body')).includes('Reconnecting'));
	assert.equal(
		await page.getByRole('button', { name: 'Pause print', exact: true }).isEnabled(),
		true
	);
	const heater = page
		.locator('form')
		.filter({ has: page.getByRole('spinbutton', { name: 'Bed target', exact: true }) });
	await heater.getByRole('spinbutton').fill('55');
	const original = await heater.locator('input[name="id"]').inputValue();
	const payload = await heater.evaluate((form) => Object.fromEntries(new FormData(form)));
	await heater.getByRole('button', { name: 'Set', exact: true }).click();
	assert.equal(new URL(page.url()).pathname, `/actions/${original}`);
	await page.getByRole('link', { name: 'Refresh status' }).click();
	assert.ok((await page.textContent('body')).includes(original));
	const replay = await native.request.post(base + '/actions', {
		headers: { Origin: base },
		form: payload,
		maxRedirects: 0
	});
	assert.ok([200, 303].includes(replay.status()), await replay.text());
	const db = new DatabaseSync(filename);
	const idle = async () => {
		for (let i = 0; i < 100; i++) {
			if (
				!db.prepare("SELECT count(*) AS n FROM actions WHERE status IN ('queued','sending')").get()
					.n
			)
				return;
			await new Promise((r) => setTimeout(r, 100));
		}
		throw new Error('Action queue did not settle');
	};
	await idle();
	assert.equal(db.prepare('SELECT count(*) AS n FROM actions WHERE id=?').get(original).n, 1);
	const csrf = await native.request.post(base + '/actions', {
		headers: { Origin: 'https://evil.example' },
		form: payload
	});
	assert.equal(csrf.status(), 403);
	await page.goto(base + '/');
	await page.getByRole('button', { name: 'Pause print', exact: true }).click();
	assert.ok(new URL(page.url()).pathname.startsWith('/actions/'));
	for (let i = 0; i < 30; i++) {
		await page.goto(base + '/');
		if (await page.getByRole('button', { name: 'Resume print', exact: true }).count()) break;
		await new Promise((r) => setTimeout(r, 100));
	}
	await page.getByRole('button', { name: 'Resume print', exact: true }).click();
	await idle();
	await page.goto(base + '/');
	await page.getByRole('button', { name: 'Stop print', exact: true }).click();
	await page.getByLabel('Nozzle after stopping').selectOption('false');
	await page.getByLabel('Bed after stopping').selectOption('false');
	await page.getByRole('checkbox', { name: 'Stop the displayed print' }).check();
	await page.getByRole('button', { name: 'Stop print', exact: true }).click();
	assert.ok(new URL(page.url()).pathname.startsWith('/actions/'));
	await idle();
	await page.goto(base + '/controls');
	assert.equal(
		await page.getByRole('spinbutton', { name: 'X (mm)', exact: true }).inputValue(),
		'110'
	);
	assert.ok(!(await page.textContent('body')).includes('Reconnecting'));
	// Upload is fixture setup through the authenticated API; native start still uses the public review form.
	const uploaded = await native.request.post(base + '/api/jobs/upload', {
		headers: { Origin: base },
		multipart: {
			file: {
				name: 'progressive.gcode',
				mimeType: 'text/plain',
				buffer: Buffer.from('; generated by OrcaSlicer\nG28\n')
			}
		}
	});
	assert.ok(uploaded.ok(), await uploaded.text());
	const file = (await uploaded.json()).file;
	await page.goto(base + `/actions?intent=start&fileId=${file.id}`);
	await page.getByRole('button', { name: 'Start print', exact: true }).click();
	assert.ok(new URL(page.url()).pathname.startsWith('/actions/'));
	await idle();
	const enhanced = await browser.newContext({
		storageState: await native.storageState(),
		viewport: { width: 1280, height: 900 }
	});
	const app = await enhanced.newPage();
	const errors = [];
	app.on('pageerror', (e) => errors.push(e.message));
	// Hold initial live transport while verifying server snapshot stays usable.
	await app.route('**/_app/remote/**/getDashboard', (route) => route.abort());
	let releaseScripts;
	const scriptsReady = new Promise((resolve) => (releaseScripts = resolve));
	await app.route('**/*.js', async (route) => {
		await scriptsReady;
		await route.continue();
	});
	await app.goto(base + '/', { waitUntil: 'commit' });
	const input = app.getByRole('spinbutton', { name: 'Bed target', exact: true });
	const enhancedHeater = app.locator('form').filter({ has: input });
	async function delayed(button, edit, form) {
		let release, received;
		const gate = new Promise((resolve) => (release = resolve)),
			intercepted = new Promise((resolve) => (received = resolve));
		const handler = async (route) => {
			const response = await route.fetch();
			received();
			await gate;
			await route.fulfill({ response });
		};
		await app.route('**/actions', handler);
		const oldId = await form.locator('[name="id"]').inputValue();
		await button.click();
		await intercepted;
		await input.fill(edit);
		release();
		await app.waitForFunction(
			(id) =>
				!Array.from(document.querySelectorAll('input[name="id"]')).some(
					(input) => input.value === id
				),
			oldId
		);
		await app.unroute('**/actions', handler);
		assert.equal(await input.inputValue(), edit, 'Acknowledgement must preserve newer draft');
	}
	await input.fill('65');
	releaseScripts();
	await app.waitForFunction(
		() =>
			document.querySelector('input[aria-label="Bed target"]')?.closest('form')?.dataset
				.enhanced === 'true'
	);
	assert.equal(await input.inputValue(), '65', 'Hydration must preserve pre-JavaScript input');
	await delayed(
		enhancedHeater.getByRole('button', { name: 'Set', exact: true }),
		'75',
		enhancedHeater
	);
	await idle();
	const cooldown = app
		.locator('form')
		.filter({ has: app.getByRole('button', { name: 'Cool down bed', exact: true }) });
	await delayed(cooldown.getByRole('button'), '85', cooldown);
	assert.equal(app.url(), base + '/', 'Enhanced submissions must not navigate');
	await idle();
	// Hold two upload bodies while submitting an independent, tiny action form.
	const cookies = (await native.cookies())
		.map((cookie) => `${cookie.name}=${cookie.value}`)
		.join('; ');
	const uploads = [0, 1].map(() => {
		const request = httpRequest(base + '/api/jobs/upload', {
			method: 'POST',
			headers: {
				Origin: base,
				Cookie: cookies,
				'Content-Type': 'multipart/form-data; boundary=slow-upload',
				'Transfer-Encoding': 'chunked'
			}
		});
		request.on('error', () => {});
		request.write(
			'--slow-upload\r\nContent-Disposition: form-data; name="file"; filename="slow.gcode"\r\nContent-Type: text/plain\r\n\r\nG28\n'
		);
		return request;
	});
	try {
		await new Promise((resolve) => setTimeout(resolve, 150));
		const started = Date.now();
		const tiny = await native.request.post(base + '/actions', {
			headers: { Origin: base, 'x-sveltekit-action': 'true', Accept: 'application/json' },
			form: { id: crypto.randomUUID(), intent: 'temperature', heater: 'bed', target: '40' }
		});
		assert.equal(tiny.status(), 200, await tiny.text());
		assert.ok(Date.now() - started < 2000, 'Basic action admission must not wait for uploads');
	} finally {
		for (const upload of uploads) upload.destroy();
	}
	// A fresh hydrated page follows raw serialized receipts through the shared stream.
	await idle();
	const feedbackPage = await enhanced.newPage();
	feedbackPage.on('pageerror', (e) => errors.push(e.message));
	let feedbackPosts = 0;
	feedbackPage.on('request', (request) => {
		if (request.method() === 'POST' && new URL(request.url()).pathname === '/actions')
			feedbackPosts++;
	});
	await feedbackPage.goto(base + '/');
	await feedbackPage.waitForFunction(
		() =>
			document.querySelector('input[aria-label="Bed target"]')?.closest('form')?.dataset
				.enhanced === 'true'
	);
	const feedbackForm = feedbackPage
		.locator('form')
		.filter({ has: feedbackPage.getByRole('spinbutton', { name: 'Bed target', exact: true }) });
	await feedbackForm.locator('[name="target"]').fill('45');
	await feedbackForm.getByRole('button', { name: 'Set', exact: true }).click();
	await feedbackForm.locator('.action-feedback').waitFor();
	await feedbackForm.evaluate((form) => form.requestSubmit());
	await idle();

	assert.equal(
		feedbackPosts,
		1,
		'Implicit resubmission must not admit a second command while the first is queued/sending'
	);
	await feedbackForm.locator('.action-feedback').waitFor({ state: 'detached', timeout: 10_000 });
	assert.equal(await feedbackForm.getByRole('link').count(), 0, 'Routine success stays quiet');
	assert.equal(
		await feedbackPage.getByRole('spinbutton', { name: 'Bed target', exact: true }).inputValue(),
		'45'
	);
	await feedbackPage.close();

	assert.ok(!(await app.textContent('body')).includes('Reconnecting to Perilune'));
	await mkdir('test-results', { recursive: true });
	await app.screenshot({ path: 'test-results/progressive-desktop.png', fullPage: true });
	await app.setViewportSize({ width: 320, height: 800 });
	// ResizeObserver-driven charts settle after the viewport resize event.
	await app.screenshot({ path: 'test-results/progressive-mobile.png', fullPage: true });
	await app.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
	// Long reconnect labels must fit even when the status changes after resizing.
	await app.locator('.connection-status').evaluate((node) => {
		node.textContent = 'Live updates unavailable';
	});
	await app.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
	assert.equal(await app.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
	assert.deepEqual(errors, []);

	db.prepare('UPDATE user SET authVersion=authVersion+1').run();
	const invalid = await native.request.get(base + '/');
	assert.ok(
		[401, 403, 303].includes(invalid.status()),
		`Invalidated session received ${invalid.status()}`
	);
	assert.ok(!(await invalid.text()).includes('Nozzle target'));
	db.close();
	console.log(
		'Progressive action smoke passed: JavaScript-disabled SSR controls, heater/pause/resume/start/stop forms, durable account-bound receipts, no replay on refresh, CSRF, enhanced no-navigation submission, initial live connection and 320px layout.'
	);
} catch (cause) {
	console.error(logs);
	throw cause;
} finally {
	await browser?.close();
	if (child) {
		child.kill('SIGTERM');
		await new Promise((resolve) =>
			child.exitCode !== null ? resolve() : child.once('exit', resolve)
		);
	}
	await rm(directory, { recursive: true, force: true });
}
