import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { chromium } from 'playwright';
import { authenticate } from './smoke-auth-helper.mjs';
const directory = await mkdtemp(join(tmpdir(), 'perilune-jobs-smoke-'));
const base = 'http://127.0.0.1:4185';
const server = spawn(process.execPath, ['scripts/server.mjs'], {
	env: {
		...process.env,
		HOST: '127.0.0.1',
		PORT: '4185',
		PERILUNE_ORIGIN: base,
		PERILUNE_DATABASE: join(directory, 'state.sqlite'),
		PERILUNE_MOONRAKER_URL: '',
		PERILUNE_MOONRAKER_API_KEY: '',
		PERILUNE_CAMERA_BASE_URL: '',
		PERILUNE_CAMERA_SOURCE: ''
	},
	stdio: ['ignore', 'pipe', 'pipe']
});
let logs = '';
server.stdout.on('data', (c) => {
	logs += c;
});
server.stderr.on('data', (c) => {
	logs += c;
});
let browser;
let page;
const png =
	'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl2nAAAAABJRU5ErkJggg==';
let gcode = `; generated by OrcaSlicer 2.4 (synthetic fixture)\n; filament_type = PLA\n; estimated printing time (normal mode) = 1h 12m\n; layer_height = 0.2\n; total layer number = 180\n; filament used [g] = 24.6\n; thumbnail begin 1x1 ${png.length}\n; ${png}\n; thumbnail end\nG28\nG1 X10 Y10\n`;
try {
	for (let attempt = 0; ; attempt++) {
		try {
			if ((await fetch(base + '/health')).ok) break;
		} catch {}
		if (server.exitCode !== null || attempt > 100) throw new Error('Jobs server failed: ' + logs);
		await new Promise((r) => setTimeout(r, 100));
	}
	browser = await chromium.launch({ headless: true });
	const context = await browser.newContext({
		viewport: { width: 1440, height: 1000 },
		colorScheme: 'light'
	});
	await authenticate(context, base, join(directory, 'state.sqlite'));
	page = await context.newPage();
	const errors = [];
	page.on('pageerror', (e) => errors.push(e.message));
	await page.goto(base + '/jobs');
	await page.getByRole('heading', { name: 'Jobs', exact: true }).waitFor();
	const thumbnail = await page.evaluate(() => {
		const canvas = document.createElement('canvas');
		canvas.width = 320;
		canvas.height = 220;
		const c = canvas.getContext('2d');
		c.fillStyle = '#182339';
		c.fillRect(0, 0, 320, 220);
		c.fillStyle = '#8bbeb4';
		c.beginPath();
		c.moveTo(75, 150);
		c.lineTo(75, 80);
		c.lineTo(180, 45);
		c.lineTo(230, 65);
		c.lineTo(230, 150);
		c.lineTo(150, 185);
		c.closePath();
		c.fill();
		c.fillStyle = '#4d8f85';
		c.beginPath();
		c.moveTo(150, 185);
		c.lineTo(150, 110);
		c.lineTo(230, 65);
		c.lineTo(230, 150);
		c.closePath();
		c.fill();
		c.fillStyle = '#182339';
		c.beginPath();
		c.ellipse(135, 97, 20, 12, -0.3, 0, Math.PI * 2);
		c.fill();
		return canvas.toDataURL('image/png').split(',')[1];
	});
	gcode = gcode.replace(
		`; thumbnail begin 1x1 ${png.length}\n; ${png}`,
		`; thumbnail begin 320x220 ${thumbnail.length}\n; ${thumbnail}`
	);
	assert.equal((await context.request.get(base + '/server/info')).status(), 200);
	await page.getByLabel('Upload G-code', { exact: true }).setInputFiles({
		name: 'fixture-bracket.gcode',
		mimeType: 'application/octet-stream',
		buffer: Buffer.from(gcode)
	});
	await page.getByRole('heading', { name: 'fixture-bracket.gcode', exact: true }).waitFor();
	await page.getByText('1h 12m', { exact: true }).waitFor();
	assert.equal(
		await page.getByRole('button', { name: 'Review & start simulation', exact: true }).isDisabled(),
		true
	);
	await page
		.getByRole('img', { name: 'Slicer preview of fixture-bracket.gcode', exact: true })
		.waitFor();
	assert.equal(
		(
			await context.request.get(
				base +
					'/api/jobs/thumbnail?id=' +
					(await (await context.request.get(base + '/api/jobs/library')).json()).files[0].id
			)
		).status(),
		200
	);
	const second = await context.newPage();
	await second.goto(base + '/jobs');
	await second.getByRole('button', { name: /fixture-bracket.gcode/ }).waitFor();
	await page.getByRole('button', { name: 'Stop print', exact: true }).click();
	await page.getByRole('dialog').getByRole('button', { name: 'Stop print', exact: true }).click();
	await page.getByRole('button', { name: 'Review & start simulation', exact: true }).waitFor();
	await page.waitForFunction(
		() =>
			![...document.querySelectorAll('button')].find(
				(b) => b.textContent.trim() === 'Review & start simulation'
			)?.disabled
	);
	await page.getByRole('button', { name: 'Review & start simulation', exact: true }).click();
	await page
		.getByRole('dialog')
		.getByRole('button', { name: 'Start simulated print', exact: true })
		.click();
	await second.getByRole('heading', { name: 'fixture-bracket.gcode', exact: true }).waitFor();
	await page.getByRole('button', { name: 'Pause print', exact: true }).click();
	await second.getByRole('button', { name: 'Resume print', exact: true }).waitFor();
	await page.getByRole('button', { name: 'Remove file…', exact: true }).click();
	await page.getByRole('dialog').getByRole('button', { name: 'Remove file', exact: true }).click();
	await page.getByRole('dialog').getByRole('alert').waitFor();
	await page.getByRole('dialog').getByRole('button', { name: 'Keep file', exact: true }).click();
	await page.getByRole('button', { name: /fixture-bracket.gcode/ }).click();
	await page.waitForFunction(() => document.querySelector('.history').innerText.includes('paused'));
	await mkdir('test-results', { recursive: true });
	await page.screenshot({ path: 'test-results/jobs-desktop.png', fullPage: true });
	await page.setViewportSize({ width: 320, height: 844 });
	assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
	await page.screenshot({ path: 'test-results/jobs-mobile.png', fullPage: true });
	await page.getByText('Send files from your slicer', { exact: true }).click();
	await page.getByRole('button', { name: 'Create upload-only key', exact: true }).click();
	await page.getByRole('textbox', { name: 'New upload key', exact: true }).waitFor();
	const token = await page
		.getByRole('textbox', { name: 'New upload key', exact: true })
		.inputValue();
	const headers = { 'X-Api-Key': token };
	const info = await fetch(base + '/server/info', { headers });
	assert.equal(info.status, 200);
	const roots = await fetch(base + '/server/files/roots', { headers });
	assert.deepEqual((await roots.json()).result, [{ name: 'gcodes', permissions: 'rw' }]);
	const form = () => {
		const data = new FormData();
		data.append('root', 'gcodes');
		data.append('print', 'false');
		data.append('file', new Blob([gcode]), 'slicer-bracket.gcode');
		return data;
	};
	const response = await fetch(base + '/server/files/upload', {
		method: 'POST',
		headers,
		body: form()
	});
	assert.equal(response.status, 200);
	const foreign = await fetch(base + '/server/files/upload', {
		method: 'POST',
		headers: { ...headers, Origin: 'https://evil.example' },
		body: form()
	});
	assert.equal(foreign.status, 403);
	assert.equal(
		(
			await fetch(base + '/server/files/upload', {
				method: 'POST',
				headers: { 'X-Api-Key': 'A'.repeat(43) },
				body: form()
			})
		).status,
		401
	);
	assert.equal((await response.json()).item.path, 'slicer-bracket.gcode');
	const duplicate = await fetch(base + '/server/files/upload', {
		method: 'POST',
		headers,
		body: form()
	});
	assert.equal(duplicate.status, 200);
	const implicit = form();
	implicit.set('print', 'true');
	assert.equal(
		(await fetch(base + '/server/files/upload', { method: 'POST', headers, body: implicit }))
			.status,
		409
	);
	assert.equal(
		(await fetch(base + '/api/jobs/library', { headers })).status,
		401,
		'upload keys cannot read the library'
	);
	assert.equal(
		(
			await fetch(base + '/printer/print/start', {
				method: 'POST',
				headers: { ...headers, 'Content-Type': 'application/json' },
				body: '{}'
			})
		).status,
		401,
		'upload keys cannot start a print'
	);
	await page.getByRole('button', { name: 'Revoke', exact: true }).click();
	await page
		.getByRole('textbox', { name: 'New upload key', exact: true })
		.waitFor({ state: 'hidden' });
	assert.equal((await fetch(base + '/server/info', { headers })).status, 401);
	await page.getByRole('button', { name: 'Stop print', exact: true }).click();
	await page.getByRole('dialog').getByRole('button', { name: 'Stop print', exact: true }).click();
	await page.waitForFunction(() =>
		document.querySelector('.current-job').innerText.includes('cancelled')
	);
	await page.getByRole('button', { name: 'Remove file…', exact: true }).click();
	await page.getByRole('dialog').getByRole('button', { name: 'Remove file', exact: true }).click();
	await page
		.getByRole('heading', { name: 'A little preparation goes a long way.', exact: true })
		.waitFor();
	assert.deepEqual(errors, []);
	console.log(
		'Jobs smoke passed: uploads, PNG proxy, metadata, shared starts/pause/cancel, deletion safeguards, history, scoped slicer uploads, revocation, 320px layout.'
	);
} catch (cause) {
	await mkdir('test-results', { recursive: true });
	await page?.screenshot({
		path: 'test-results/jobs-failure.png',
		fullPage: true,
		mask: [page.getByRole('textbox', { name: 'New upload key' })]
	});
	console.error(logs);
	throw cause;
} finally {
	await browser?.close();
	server.kill('SIGTERM');
	await new Promise((r) => server.once('exit', r));
	await rm(directory, { recursive: true, force: true });
}
